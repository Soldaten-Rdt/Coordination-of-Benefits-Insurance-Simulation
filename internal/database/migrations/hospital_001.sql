CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    role_title TEXT NOT NULL,
    role TEXT NOT NULL,
    hospital_name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS system_configs (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code TEXT NOT NULL UNIQUE,
    nik CHAR(16) NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    birth_date DATE NOT NULL,
    gender CHAR(1) NOT NULL CHECK (gender IN ('L','P')),
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    emergency_contact_name TEXT NOT NULL DEFAULT '',
    emergency_contact_phone TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS patient_coverages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE CASCADE,
    payer_tier TEXT NOT NULL CHECK (payer_tier IN ('PRIMARY','SECONDARY','TERTIARY')),
    payer_type TEXT NOT NULL CHECK (payer_type IN ('BPJS','PRIVATE_INSURANCE')),
    insurer_name TEXT NOT NULL,
    card_or_policy_number TEXT NOT NULL,
    care_class TEXT NOT NULL DEFAULT '',
    primary_faskes TEXT NOT NULL DEFAULT '',
    plan_name TEXT NOT NULL DEFAULT '',
    annual_limit BIGINT NOT NULL DEFAULT 0 CHECK (annual_limit >= 0),
    remaining_limit BIGINT NOT NULL DEFAULT 0 CHECK (remaining_limit >= 0),
    room_daily_limit BIGINT NOT NULL DEFAULT 0 CHECK (room_daily_limit >= 0),
    valid_until DATE,
    status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','EXPIRED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (payer_type, card_or_policy_number)
);
CREATE TABLE IF NOT EXISTS medical_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number TEXT NOT NULL UNIQUE,
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    care_type TEXT NOT NULL CHECK (care_type IN ('RAWAT_INAP','RAWAT_JALAN')),
    room_name TEXT NOT NULL DEFAULT '',
    entitled_class TEXT NOT NULL DEFAULT '',
    dpjp_name TEXT NOT NULL,
    admission_date DATE NOT NULL,
    discharge_date DATE,
    diagnosis_icd10 TEXT NOT NULL,
    diagnosis_desc TEXT NOT NULL DEFAULT '',
    procedure_icd9 TEXT NOT NULL DEFAULT '',
    procedure_desc TEXT NOT NULL DEFAULT '',
    ina_cbg_code TEXT NOT NULL DEFAULT '',
    ina_cbg_tariff BIGINT NOT NULL DEFAULT 0 CHECK (ina_cbg_tariff >= 0),
    total_hospital_bill BIGINT NOT NULL DEFAULT 0 CHECK (total_hospital_bill >= 0),
    simulation_mode TEXT NOT NULL CHECK (simulation_mode IN ('COB','NON_COB')),
    workflow_step SMALLINT NOT NULL DEFAULT 1 CHECK (workflow_step BETWEEN 1 AND 6),
    coordination_status TEXT NOT NULL DEFAULT 'IN_PROGRESS',
    payment_status TEXT NOT NULL DEFAULT 'UNPAID' CHECK (payment_status IN ('UNPAID','PARTIAL','PAID')),
    discharge_documents_complete BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS case_bill_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES medical_cases(id) ON DELETE CASCADE,
    category TEXT NOT NULL CHECK (category IN ('AKOMODASI','TINDAKAN','FARMASI','LABORATORIUM')),
    description TEXT NOT NULL,
    unit_info TEXT NOT NULL DEFAULT '',
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
    subtotal BIGINT NOT NULL CHECK (subtotal >= 0),
    bpjs_portion BIGINT NOT NULL DEFAULT 0,
    insurer_portion BIGINT NOT NULL DEFAULT 0,
    patient_portion BIGINT NOT NULL DEFAULT 0,
    validation_status TEXT NOT NULL DEFAULT 'VALID'
);
CREATE TABLE IF NOT EXISTS subclaims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subclaim_code TEXT NOT NULL UNIQUE,
    case_id BIGINT NOT NULL REFERENCES medical_cases(id) ON DELETE CASCADE,
    coverage_id BIGINT REFERENCES patient_coverages(id),
    payer_type TEXT NOT NULL CHECK (payer_type IN ('BPJS','PRIVATE_INSURANCE')),
    payer_name TEXT NOT NULL,
    sep_number TEXT NOT NULL DEFAULT '',
    requested_amount BIGINT NOT NULL DEFAULT 0 CHECK (requested_amount >= 0),
    approved_amount BIGINT NOT NULL DEFAULT 0 CHECK (approved_amount >= 0),
    non_cover_deduction BIGINT NOT NULL DEFAULT 0 CHECK (non_cover_deduction >= 0),
    deduction_reason TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','SUBMITTED','IN_REVIEW','REVISION_REQUIRED','APPROVED','REJECTED')),
    reviewer_name TEXT NOT NULL DEFAULT '',
    reviewer_notes TEXT NOT NULL DEFAULT '',
    last_synced_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS case_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT REFERENCES medical_cases(id) ON DELETE CASCADE,
    patient_id BIGINT REFERENCES patients(id) ON DELETE CASCADE,
    target_payer TEXT NOT NULL CHECK (target_payer IN ('GENERAL','BPJS','PRIVATE_INSURANCE')),
    doc_type TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_url TEXT NOT NULL,
    file_size BIGINT NOT NULL DEFAULT 0,
    mime_type TEXT NOT NULL DEFAULT '',
    is_mandatory BOOLEAN NOT NULL DEFAULT FALSE,
    is_critical_discharge BOOLEAN NOT NULL DEFAULT FALSE,
    validation_status TEXT NOT NULL DEFAULT 'VALID',
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (case_id IS NOT NULL OR patient_id IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS split_bill_simulations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL UNIQUE REFERENCES medical_cases(id) ON DELETE CASCADE,
    preset_name TEXT NOT NULL DEFAULT '',
    bpjs_percent NUMERIC(6,2) NOT NULL DEFAULT 0,
    insurer_percent NUMERIC(6,2) NOT NULL DEFAULT 0,
    patient_percent NUMERIC(6,2) NOT NULL DEFAULT 0,
    total_bill BIGINT NOT NULL,
    reference_tariff BIGINT NOT NULL DEFAULT 0,
    bpjs_estimated BIGINT NOT NULL DEFAULT 0,
    insurer_estimated BIGINT NOT NULL DEFAULT 0,
    patient_estimated BIGINT NOT NULL DEFAULT 0,
    bpjs_approved BIGINT NOT NULL DEFAULT 0,
    insurer_approved BIGINT NOT NULL DEFAULT 0,
    patient_final_excess BIGINT NOT NULL DEFAULT 0,
    notes TEXT NOT NULL DEFAULT '',
    is_applied BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_code TEXT NOT NULL UNIQUE,
    case_id BIGINT NOT NULL REFERENCES medical_cases(id),
    subclaim_id BIGINT REFERENCES subclaims(id),
    payer_source TEXT NOT NULL CHECK (payer_source IN ('BPJS','PRIVATE_INSURANCE','PATIENT')),
    payer_label TEXT NOT NULL DEFAULT '',
    payment_method TEXT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount > 0),
    bank_reference TEXT NOT NULL DEFAULT '',
    cashier_name TEXT NOT NULL DEFAULT '',
    paid_at TIMESTAMPTZ NOT NULL,
    verification_status TEXT NOT NULL DEFAULT 'VERIFIED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS case_communications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES medical_cases(id) ON DELETE CASCADE,
    subclaim_id BIGINT REFERENCES subclaims(id),
    sender_role TEXT NOT NULL,
    sender_name TEXT NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT REFERENCES medical_cases(id) ON DELETE CASCADE,
    patient_id BIGINT REFERENCES patients(id) ON DELETE CASCADE,
    actor_name TEXT NOT NULL DEFAULT 'System',
    actor_role TEXT NOT NULL DEFAULT 'SYSTEM',
    event_type TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT REFERENCES medical_cases(id) ON DELETE CASCADE,
    subclaim_code TEXT NOT NULL DEFAULT '',
    source_payer TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_cases_patient_created ON medical_cases(patient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_payments_case_payer ON payment_transactions(case_id, payer_source);
CREATE INDEX IF NOT EXISTS idx_docs_case_target ON case_documents(case_id, target_payer);
CREATE INDEX IF NOT EXISTS idx_subclaims_case ON subclaims(case_id);
