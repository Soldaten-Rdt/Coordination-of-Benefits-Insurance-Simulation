CREATE TABLE IF NOT EXISTS bpjs_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    role_title TEXT NOT NULL,
    branch_name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS bpjs_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subclaim_code TEXT NOT NULL UNIQUE,
    case_number TEXT NOT NULL,
    hospital_name TEXT NOT NULL,
    patient_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    coverage_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    clinical_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    financial_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    documents_snapshot JSONB NOT NULL DEFAULT '[]'::jsonb,
    sla_deadline TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'SUBMITTED',
    requested_amount BIGINT NOT NULL DEFAULT 0,
    approved_amount BIGINT NOT NULL DEFAULT 0,
    compliance_checks JSONB NOT NULL DEFAULT '{}'::jsonb,
    reviewer_id BIGINT REFERENCES bpjs_users(id),
    reviewer_notes TEXT NOT NULL DEFAULT '',
    decided_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS bpjs_claim_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL REFERENCES bpjs_claims(id) ON DELETE CASCADE,
    actor_name TEXT NOT NULL,
    action TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
