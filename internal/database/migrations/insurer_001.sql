CREATE TABLE IF NOT EXISTS insurer_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    role_title TEXT NOT NULL,
    insurer_entity_name TEXT NOT NULL,
    authority_limit BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS insurer_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subclaim_code TEXT NOT NULL UNIQUE,
    case_number TEXT NOT NULL,
    hospital_name TEXT NOT NULL,
    insurer_entity_name TEXT NOT NULL DEFAULT '',
    patient_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    policy_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    clinical_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    cost_breakdown_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    documents_snapshot JSONB NOT NULL DEFAULT '[]'::jsonb,
    status TEXT NOT NULL DEFAULT 'SUBMITTED',
    requested_amount BIGINT NOT NULL DEFAULT 0,
    non_cover_deduction BIGINT NOT NULL DEFAULT 0,
    deduction_reason TEXT NOT NULL DEFAULT '',
    approved_amount BIGINT NOT NULL DEFAULT 0,
    patient_excess_impact BIGINT NOT NULL DEFAULT 0,
    reviewer_id BIGINT REFERENCES insurer_users(id),
    reviewer_notes TEXT NOT NULL DEFAULT '',
    decided_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS insurer_claim_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL REFERENCES insurer_claims(id) ON DELETE CASCADE,
    actor_name TEXT NOT NULL,
    action TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
